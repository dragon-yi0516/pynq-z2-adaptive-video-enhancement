"""从 registers.csv 生成 Python 寄存器封装 + Markdown 表。

用法：
    python3 gen_host.py --csv registers.csv --out regs_gen.py --md regs.md
"""
import argparse
import csv
import os


def read_regs(path):
    regs = []
    with open(path, newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            off = int(row["offset"], 0)
            regs.append({
                "offset": off,
                "name": row["name"].strip(),
                "access": row.get("access", "RW").strip().upper(),
                "width": int(row.get("width", "32")),
                "description": row.get("description", "").strip(),
            })
    regs.sort(key=lambda r: r["offset"])
    return regs


def gen_python(regs):
    lines = [
        "# auto-generated by gen_host.py; do not edit by hand",
        "",
        "OFFSETS = {",
    ]
    for r in regs:
        lines.append('    "%s": 0x%02X,' % (r["name"], r["offset"]))
    lines += [
        "}",
        "",
        "",
        "class RegisterBank:",
        "    \"\"\"Minimal AXI-Lite register wrapper.",
        "",
        "    ip must provide read(offset) and write(offset, value).",
        "    \"\"\"",
        "",
        "    def __init__(self, ip):",
        "        self.ip = ip",
        "",
        "    def read(self, name):",
        "        return int(self.ip.read(OFFSETS[name])) & 0xFFFFFFFF",
        "",
        "    def write(self, name, value):",
        "        self.ip.write(OFFSETS[name], int(value) & 0xFFFFFFFF)",
        "",
    ]
    return "\n".join(lines)


def gen_markdown(regs):
    lines = [
        "| Offset | Name | Access | Width | Description |",
        "|---|---|---|---|---|",
    ]
    for r in regs:
        lines.append("| 0x%02X | `%s` | %s | %d | %s |"
                     % (r["offset"], r["name"], r["access"],
                        r["width"], r["description"]))
    return "\n".join(lines) + "\n"


def main():
    p = argparse.ArgumentParser(description="AXI-Lite register contract generator")
    p.add_argument("--csv", required=True)
    p.add_argument("--out", default="regs_gen.py")
    p.add_argument("--md", default="")
    args = p.parse_args()

    regs = read_regs(args.csv)
    out = os.path.abspath(args.out)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(gen_python(regs))
    print("wrote", out, "(%d registers)" % len(regs))

    if args.md:
        md = os.path.abspath(args.md)
        os.makedirs(os.path.dirname(md), exist_ok=True)
        with open(md, "w", encoding="utf-8") as fh:
            fh.write(gen_markdown(regs))
        print("wrote", md)


if __name__ == "__main__":
    main()
