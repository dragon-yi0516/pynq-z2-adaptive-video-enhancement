"""生成 HLS 用的测试向量（不依赖 Jupyter，虚拟机里直接 python3 跑）。

做的事和 05_mlp_verify.ipynb 完全一样：
  1. 把 weights/mlp_weights.h 同步到 stage05_mlp_hls/src/ ；
  2. 从 data/features.csv 里每类抽若干条（加上几条边界样本），
     用 Python 的定点参考实现算出期望类别，写成 src/tv_mlp.h 。

用法（在虚拟机或板子上都行）：
    cd <ai_video>/..
    python3 ai_video/stage05_mlp_hls/make_tv.py

或者从 ai_video 目录里：
    python3 stage05_mlp_hls/make_tv.py

注意：需要 numpy。虚拟机里如果没有，可以先
    sudo apt install -y python3-numpy
或者干脆在板子上跑 05_mlp_verify.ipynb（板子一定装了 numpy）。
"""
import os
import sys


def find_root(start):
    """往上找含 lib/video_setup.py 的目录。"""
    d = os.path.abspath(start)
    for _ in range(8):
        if os.path.isfile(os.path.join(d, "lib", "video_setup.py")):
            return d
        parent = os.path.dirname(d)
        if parent == d:
            break
        d = parent
    return None


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = find_root(os.getcwd()) or find_root(here)
    if root is None:
        print("[ERROR] 找不到工程根目录（应含 lib/video_setup.py）")
        return 1

    try:
        import numpy as np
    except ImportError:
        print("[ERROR] 这个脚本需要 numpy。装一个：sudo apt install -y python3-numpy")
        print("        或者改在板子上跑 05_mlp_verify.ipynb（板子一定装了 numpy）。")
        return 1

    sys.path.insert(0, root)
    sys.path.insert(0, os.path.join(root, "stage04_mlp_train"))

    import mlp_common as mc
    from lib import features_io

    stage5 = os.path.join(root, "stage05_mlp_hls")
    src_dir = os.path.join(stage5, "src")
    os.makedirs(src_dir, exist_ok=True)

    import hashlib

    # ---- 1. 同步权重头文件 ------------------------------------------------
    src_h = os.path.join(root, "weights", "mlp_weights.h")
    if not os.path.exists(src_h):
        print("[ERROR] 缺少 %s\n        请先完成阶段 4（03/04 两个 notebook）。" % src_h)
        return 1
    header_text = open(src_h, encoding="utf-8").read()
    dst_h = os.path.join(src_dir, "mlp_weights.h")
    with open(dst_h, "w", encoding="utf-8") as f:
        f.write(header_text)
    qmodel = mc.from_c_header(header_text)
    # 把权重的指纹写进 tv_mlp.h，HLS 的脚本会拿它对一遍。
    # 为什么要这个：第一次踩的坑就是 src/mlp_weights.h 已经是新权重、
    # 但 src/tv_mlp.h 还是用旧权重算的，csim 报了一堆 MISMATCH，
    # 看着像 C 代码有 bug，其实是两批文件不同代。
    w_sha = hashlib.sha256(header_text.encode("utf-8")).hexdigest()
    print("已同步权重头文件 ->", dst_h)
    print("权重指纹 sha256 =", w_sha[:16], "...")
    print("INPUT_SHIFT = %d, HIDDEN = %d, OUTPUT = %d"
          % (qmodel["input_shift"], qmodel["w1"].shape[1], qmodel["w2"].shape[1]))

    # ---- 2. 挑测试向量 -----------------------------------------------------
    csv_path, kind = features_io.pick_features_csv(root)
    print("测试向量取自:", os.path.basename(csv_path), "(%s)" % kind)
    X, y = features_io.load_csv(csv_path)

    picked = []
    for k in sorted(set(y.tolist())):
        picked.extend(np.where(y == k)[0][:40].tolist())
    vectors = [[int(round(float(v))) for v in X[i]] for i in picked]
    # 再加 4 条边界样本：全 0 / 全最大 / 全 1 / 高亮度低梯度。
    # 目的不是"有意义的数据"，而是把饱和、移位、下标约定这些边界情况逼出来，
    # 让 Python 参考实现和 HLS 实现在这几个点上必须给出同一个答案。
    for edge in ([0, 0, 0], [255, 255, 255], [1, 1, 1], [200, 250, 60]):
        vectors.append(list(edge))

    expected = [mc.predict_fixed_raw(qmodel, v[0], v[1], v[2]) for v in vectors]

    # ---- 3. 写 tv_mlp.h ---------------------------------------------------
    lines = []
    lines.append("// auto-generated by stage05_mlp_hls/make_tv.py\n")
    lines.append("// AI_VIDEO_WEIGHTS_SHA256: %s\n" % w_sha)
    # 这一行是权重指纹；script.tcl 会拿它对 src/mlp_weights.h 校验，
    # 确保测试向量和权重是同一代（避免 csim 报一堆假 MISMATCH）。
    # 注释故意写成 ASCII：这个头文件会被 gcc 编译，非 ASCII 注释虽然一般没问题，
    # 但没必要冒这个险。
    lines.append("// (weights fingerprint; checked by script.tcl against src/mlp_weights.h)\n")
    lines.append("#ifndef AI_VIDEO_TV_MLP_H\n#define AI_VIDEO_TV_MLP_H\n\n")
    lines.append("#define TV_N %d\n\n" % len(vectors))
    lines.append("static const short TV_X[TV_N][3] = {\n")
    lines.append(",\n".join("    {%d,%d,%d}" % tuple(v) for v in vectors))
    lines.append("\n};\n\n")
    lines.append("static const int TV_Y[TV_N] = {\n    ")
    lines.append(",".join(str(int(e)) for e in expected))
    lines.append("\n};\n\n#endif\n")

    tv_path = os.path.join(src_dir, "tv_mlp.h")
    with open(tv_path, "w", encoding="utf-8") as f:
        f.write("".join(lines))

    dist = {}
    for e in expected:
        dist[e] = dist.get(e, 0) + 1
    print("已写出:", tv_path)
    print("测试向量数:", len(vectors), " 期望类别分布:", dist)
    print("")
    print("下一步：")
    print("    source /tools/Xilinx/Vivado/2024.2/settings64.sh")
    print("    cd %s" % os.path.join(stage5, "hls"))
    print("    vivado_hls -f script.tcl")
    print("必须看到:  CSIM PASSED: HLS 与 Python 定点参考完全一致")
    return 0


if __name__ == "__main__":
    sys.exit(main())
